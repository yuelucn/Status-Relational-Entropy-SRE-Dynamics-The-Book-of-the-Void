    print("     Step 1  先写下指数律 + p_graph 的形（纯图量，不含自由参数）")
    print("     Step 2  把 T½ 当作**对 p_graph 的独立检验**（而非第 2 个方程）")
    print("     => 这与 L1 判据的成功模式相同：**零参数、只作证伪门槛**。")

    print("\n" + "=" * 80)
    print("判定结果：直接联立反解 **不可行（欠定）**；")
    print("          但可改写为『零参数判据 + 独立检验』模式，与 L1 同型。")
    print("=" * 80)

    verdict = ("直接联立反解不可行（2 方程 vs 未知数随 A 增长 + 未定义的 p_graph/p_env 泛函）；"
               "与 §12.12 同型，结论同为欠定")
    print("\nverdict = %s" % verdict)


