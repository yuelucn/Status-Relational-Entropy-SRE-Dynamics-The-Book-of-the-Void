def main():
    print("=" * 80)
    print("反解可行性核算：半衰期 + 电子轨道数 + 核子数 能否联立反解核图表达？")
    print("=" * 80)

    print("\n[A] 用户设想的方程逐条清点")
    print("-" * 80)
    n_eq = 0
    for e in EQUATIONS:
        print("  %-26s -> %s" % (e["name"], e["gives"]))
        print("      独立方程数贡献：%d" % e["n_independent"])
        print("      %s" % e["note"])
        n_eq += e["n_independent"]
        print()
    print("  >>> 三条观测量的**独立方程总数 = %d**" % n_eq)

    print("\n[B] 待反解的未知量（核子层图表达的自由度）")
    print("-" * 80)
    for u in UNKNOWNS:
        print("  %-22s 自由度：%s" % (u["name"], u["n_free"]))
        print("      %s" % u["note"])
    print()
    print("  说明：骨架 Y3 本身 V/E/β1 已定死（三步筛选唯一）。")
    print("        挂点 sigma 已被自同构吸收 = 0 自由度（实测）。")
    print("        => **唯一真自由度 = k 的分布**。")

    print("\n[C] 从图到观测量的泛函：它们的『形』被定住了吗？")
    print("-" * 80)
    for f in FUNCTIONALS:
        print("  %-45s [%s]" % (f["name"], f["status"]))
        print("      %s" % f["note"])
    print()

    print("[D] 同型先例（§12.12 已实测，结论为负）")
    print("-" * 80)
    p = PRECEDENT
    print("  %s" % p["what"])
    print("    方程数 = %d ；未知数 = %s" % (p["equations"], p["unknowns"]))
    print("    结果 = %s" % p["result"])
    print("    判定 = %s" % p["verdict"])
    print("  => 这说明：**该型核算在本项目已做过，且结论是欠定。**")

    print("\n[E] 把同一核算套到『半衰期版』")
    print("-" * 80)
    print("  方程：")
    print("     (1) A           -> 1 个（且 A 不进结构，只进账本）")
    print("     (2) 电子轨道数    -> 0 个（介观层，按硬约束不进核子拼接）")
    print("     (3) T½          -> 1 个（标量）")
    print("     ---- 合计 = 2 个独立方程 ----")
    print()
    print("  未知数：")
    print("     k 分布           -> n_group(A) - 1 个（A>=4 时 >= 1，且随 A 增长）")
    print("     p_graph 的形      -> 未定义")
    print("     p_env 的形        -> 未定义（只有现象学分层）")
    print()
    print("  => 方程 2 个 vs 未知数『k 分布 + 2 个未定义的泛函』。")

    print("\n[F] 判定")
    print("-" * 80)
    print("  1) **直接联立不可行**：2 个方程 < 未知数（k 分布随 A 增长 + 2 个泛函）。")
    print("     且与 §12.12 同型，结论同为**欠定**。")
    print()
    print("  2) **电子轨道数不给核子层方程**（硬约束）。但它是另一条路的入口：")
    print("     它不是『核子层的第 3 个方程』，而是**p_env 那一侧的可测量**（见补充六）。")
    print()
    print("  3) **真正的缺口不在方程数，而在两个泛函的『形』**：")
    print("     · 指数律 × p_graph  —— 可导但未写（最大空缺）")
    print("     · p_env 从图量的映射 —— 有实测分层但未映射")
