# -*- coding: utf-8 -*-
"""
MLP 代理模型可行性诊断：SRE「图不变量 -> 观测量」能用 MLP 猜吗？

【用户设想（2026-09-23）】
SRE 数理支撑不完善，只有基本算子、没有整套方程体系，直接解方程极难；
但可以设计一个 MLP 模型来「猜」这个映射。

【为什么必须先用诊断脚本而不是直接建 MLP】
项目既有明文约定（Final_Report_1.0_C §6.3）：
  「优先树集成（RF / XGBoost）……而非黑盒深度网络——因为树模型可输出
    不确定性、可解释性强、小样本更稳。」
  「不推荐：样本太少必然过拟合，模型只是记忆现有 case。」
⇒ 所以必须先回答「样本够不够」，再谈「用什么模型」。这是判据先于模型。

【样本规模的真实盘点（本会话已确立的事实）】
SRE 核子层目前的可用样本 = **A<=4 的已测核 = 4 个**（d / 3H / 3He / 4He）。
  - 结合能**数值**：A>=4 不可算（§12.11(2) 恒等式锁定）
  - 存在性：A=4 可算（L1 判据 8/8），A>=5 不可（§12.12，22/34）
  - T½：项目从未做过（补充六/七）
⇒ 这是「4 个样本」。

【本脚本做什么】
不训练任何模型（因为样本不够），而是做三件事：
  (1) 精确计算「4 个样本」在参数空间里能支撑什么；
  (2) 算出「要支撑一个给定容量的模型，需要多少样本」；
  (3) 给出「哪些路线能在不引入自由参数的前提下扩大样本」。
"""
import math

# ---------------------------------------------------------------------------
# [A] 可用样本的真实盘点
# ---------------------------------------------------------------------------
SAMPLES = [
    dict(name="d",   A=2, Z=1, N=1, k_dist="(2)",     note="氘核，B=2.2245 MeV"),
    dict(name="3H",  A=3, Z=1, N=2, k_dist="(3)",     note="氚，B=8.4818 MeV"),
    dict(name="3He", A=3, Z=2, N=1, k_dist="(3)",     note="氦-3，B=7.7181 MeV"),
    dict(name="4He", A=4, Z=2, N=2, k_dist="(4)",     note="氦-4，B=28.2957 MeV"),
]

# 本会话已确立：进结构的唯一量 = k 分布；A 与 p/n 分布不进结构
# 故 4 个样本的「结构侧」实际只有 3 个不同的 k 分布：(2), (3), (4)
K_DISTS = {"(2)": ["d"], "(3)": ["3H", "3He"], "(4)": ["4He"]}

# 账本侧剖面 = (#p, A, A)
LEDGERS = {"d": (1, 2, 2), "3H": (1, 3, 3), "3He": (2, 3, 3), "4He": (2, 4, 4)}


def main():
    print("=" * 80)
    print("MLP 代理模型可行性诊断：样本够不够？")
    print("=" * 80)

    print("\n[A] 真实可用的样本盘点（SRE 核子层）")
    print("-" * 80)
    print("  %-6s %-4s %-4s %-4s %-9s %s" %
          ("核", "A", "Z", "N", "k 分布", "备注"))
    for s in SAMPLES:
        print("  %-6s %-4d %-4d %-4d %-9s %s" %
              (s["name"], s["A"], s["Z"], s["N"], s["k_dist"], s["note"]))
    n = len(SAMPLES)
    print("\n  >>> 样本总数 n = %d" % n)

    print("\n[B] 结构侧的有效区分度（关键）")
    print("-" * 80)
    print("  本会话已确立：**进结构的唯一量是 k 分布**（A 与 p/n 不进结构）。")
    for kd, names in K_DISTS.items():
        print("    k 分布 %-6s : %s" % (kd, ", ".join(names)))
    print("  => 4 个样本在**结构侧只有 %d 个不同的取值**。" % len(K_DISTS))
    print()
    print("  账本侧剖面 (#p, A, A)：")
    for nm, lg in LEDGERS.items():
        print("    %-5s -> %s" % (nm, lg))
    print("  => 账本侧也只有 4 个不同取值，且 3H/3He 的 A 相同、#p 差 1。")

    print("\n[C] 模型容量的核算：支撑一个模型需要多少样本？")
    print("-" * 80)
    # 经验法则：每个可训练参数至少需要 ~10 个样本（保守 5，宽松 20）
    for label, spc in [("保守（20 样本/参数）", 20),
                       ("常用（10 样本/参数）", 10),
                       ("激进（5 样本/参数）", 5)]:
        print("  %-22s : 用 %d 个样本最多支撑 %.1f 个参数"
              % (label, n, n / spc))
    print()
    print("  参照：")
    print("    - 一个最小 MLP（1 隐层 8 神经元, 1 维输入 1 维输出）")
    print("      = 8 + 8 + 1 = 17 个参数")
    print("    => 即使最激进的 5 样本/参数，也只够 %.1f 个参数 < 17。" % (n / 5))
    print("    - 若输入含 k 分布 + 账本剖面（~2-3 维），参数只会更多。")
    print()
    print("  >>> **结论：n=4 连一个最小 MLP 都撑不住。**")

    print("\n[D] 那 n=4 能做什么？—— 能做「零参数判据」，不能做「拟合」")
    print("-" * 80)
    print("  本会话的成功先例正是零参数判据：")
    print("    L1 判据 |n_n - n_p| <= 1：**0 个参数**，在 A<=4 上 8/8。")
    print("    它没有『拟合』任何东西，是**先写死判据、再看数据**。")
    print()
    print("  => 在 n=4 上，正确做法不是 MLP，而是：")
    print("     写下一个**零自由参数**的映射假设，然后用 4 个点做**证伪检验**。")
    print("     4 个点足以证伪（一个反例即死），但不足以拟合（无法防过拟合）。")

    print("\n[E] 要真正上 MLP，样本从哪来？（三条路线）")
    print("-" * 80)
    print("  路线 1  扩大 A 范围 —— **被阻断**：")
    print("           A>=4 结合能数值不可算（恒等式锁定）；T½ 项目从未涉及。")
    print("           => 需要先解决 §12.11(2) 的恒等式，成本高。")
    print()
    print("  路线 2  **自造样本（SRE 内部）** —— 推荐：")
    print("           用 _sre_nucleon_structure_vs_ledger.py 的装配器，")
    print("           对 A=4..12 枚举**所有可行 k 分布**，算出每种的图不变量")
    print("           (V/E/β1/T/ρ/λ2/|Aut|)。这是**纯 SRE 内部生成**，")
    print("           样本量可达数百，且标签（图不变量）精确无噪声。")
    print("           => 这是唯一能**无成本扩大样本**的路线。")
    print()
    print("  路线 3  引入实测观测量作标签 —— 受限：")
    print("           结合能只有 A<=4 的 4 个可用；T½ 未做。")
    print("           => 只能作**检验集**，不能作训练集。")

    print("\n[F] 建议的正确架构（若坚持用 MLP）")
    print("-" * 80)
    print("  ┌ 训练集：路线 2 自造的 (k 分布 -> 图不变量) 数百样本")
    print("  │   —— 这是『代理求解器』：MLP 学的是**本可精确计算**的图量,")
    print("  │      用于把昂贵的图计算替换成快速近似（合法用途）。")
    print("  │")
    print("  └ 检验集：A<=4 的 4 个实测核 + NIST/JEFF 半衰期数据")
    print("      —— 这才是『猜物理』的那一步，且只能用零参数判据。")
    print()
    print("  ⚠ 关键警告：**不能让 MLP 直接学『k 分布 -> 实测半衰期』**。")
    print("     原因：训练样本若只有 4 个，MLP 必然退化为查表；")
    print("           若把自造样本当标签训练，则标签本身没有物理真值。")
    print("           ⇒ 必须分清『代理求解器』与『物理预测器』两种角色。")

    print("\n" + "=" * 80)
    print("判定：以现有样本量(n=4)，**直接上 MLP 不可行**（自由度远超样本数）。")
    print("      可行路径 = ①零参数判据做检验（立即可做）")
    print("                ②SRE 内部枚举自造样本（用于代理求解器，非物理预测）")
    print("=" * 80)


if __name__ == "__main__":
    main()
