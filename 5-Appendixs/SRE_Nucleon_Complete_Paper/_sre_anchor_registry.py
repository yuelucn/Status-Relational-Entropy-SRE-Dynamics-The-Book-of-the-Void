def cubic_sample(V, n_target, seed):
    rng = np.random.default_rng(seed)
    pool, seen_sig = [], {}
    tries = 0
    while len(pool) < n_target and tries < n_target * 120:
        tries += 1
        H = nx.configuration_model([3] * V, seed=int(rng.integers(1 << 31)))
        G = nx.Graph(H)
        G.remove_edges_from(nx.selfloop_edges(G))
        if G.number_of_edges() != 3 * V // 2 or not nx.is_connected(G):
            continue
        ev = np.linalg.eigvalsh(nx.laplacian_matrix(G).toarray().astype(float))
        sig = tuple(np.round(ev, 6))
        if sig in seen_sig:
            continue
        # 同构去重（小样本内两两比）
        dup = False
        for X in pool:
            if nx.is_isomorphic(G, X):
                dup = True
                break
        if dup:
            continue
        seen_sig[sig] = 1
        pool.append(G)
    return np.array([pi1(G) for G in pool]), pool


