def rand_rho_seq(k, n=400, seed=0):
    """同**度序列**的随机连通图的 rho 序列（对照基线）。

    注意：共享环 k 体骨架**不是** 3-正则图（共享环三点度为 k+2），
    故不能用「随机 3-正则图」作对照 —— 必须用同度序列配置模型。
    度序列 = [k+2, k+2, k+2] + [3]*(9k)。"""
    V, E = Vk(k), Ek(k)
    dsq = [k + 2, k + 2, k + 2] + [3] * (9 * k)
    assert sum(dsq) == 2 * E and len(dsq) == V, (V, E, len(dsq))
    rng = np.random.default_rng(seed)
    out = []
    tries = 0
    while len(out) < n and tries < n * 60:
        tries += 1
        H = nx.configuration_model(dsq, seed=int(rng.integers(1 << 31)))
        G = nx.Graph(H)
        G.remove_edges_from(nx.selfloop_edges(G))
        # 去掉平行边后度可能变；只保留同 (V,E) 且连通的
        if G.number_of_edges() != E or not nx.is_connected(G):
            continue
        ev = np.linalg.eigvalsh(nx.laplacian_matrix(G).toarray().astype(float))
        out.append(float(ev[-1]))
    return np.array(out)


