def mobius_pi1(n, w=1.0):
    """Möbius 阶梯 M_n 的闭式 Π₁ = 4sin²(2π/n) / (2+2w+2cos(2π/n))。"""
    x = 2.0 * np.pi / n
    return 4.0 * np.sin(x) ** 2 / (2.0 + 2.0 * w + 2.0 * np.cos(x))


def Y3(pre="", state="p", r=0):
    G = nx.Graph()
    for i in range(3):
        for j in range(3):
            G.add_edge("%sc%d" % (pre, i), "%sL%d%d" % (pre, i, j))
    for j in range(3):
        for a, b in ((0, 1), (1, 2), (2, 0)):
            G.add_edge("%sL%d%d" % (pre, a, j), "%sL%d%d" % (pre, b, j))
    if state == "n":
        G.remove_edge("%sL0%d" % (pre, r), "%sL1%d" % (pre, r))
    return G


def pi1(G):
    ev = np.sort(np.linalg.eigvalsh(nx.laplacian_matrix(G).toarray().astype(float)))
    return float(ev[1] / ev[-1])


