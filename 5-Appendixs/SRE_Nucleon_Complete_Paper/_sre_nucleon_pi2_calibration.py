# ==================================================================== 电子侧
def mobius_L(n, w):
    """Möbius 阶梯 M_n（环 C_n + 对径弦权 w）的组合 Laplacian 谱（升序）。"""
    A = np.zeros((n, n))
    h = n // 2
    for i in range(n):
        A[i, (i + 1) % n] = 1.0
        A[(i + 1) % n, i] = 1.0
    for i in range(h):
        A[i, i + h] = w
        A[i + h, i] = w
    return np.sort(np.linalg.eigvalsh(np.diag(A.sum(1)) - A))


def mobius_closed(n, w):
    """闭式 μ_k(w) = (2+w) − 2cos(2πk/n) − w·(−1)^k（论文 §7.3）。"""
    return np.sort(np.array(
        [(2 + w) - 2 * np.cos(2 * np.pi * k / n) - w * ((-1) ** k)
         for k in range(n)]))


def k_of_index(n, w, idx):
    """排序后第 idx 个特征值对应哪个 k（同时给出 parity 与 w 相关性）。"""
    rows = []
    for k in range(n):
        v = (2 + w) - 2 * np.cos(2 * np.pi * k / n) - w * ((-1) ** k)
        v_alt = (2 + 1.5) - 2 * np.cos(2 * np.pi * k / n) - 1.5 * ((-1) ** k)
        rows.append((round(v, 12), k, abs(v - v_alt) < 1e-12))
    rows.sort()
    return rows[idx]


