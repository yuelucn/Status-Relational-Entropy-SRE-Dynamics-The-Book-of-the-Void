def log_width(arr):
    return float(np.log(arr.max()) - np.log(arr.min())) if arr.max() > arr.min() else 0.0


def exp_hits(arr, win=0.01):
    n = len(arr)
    w = log_width(arr)
    return n * (2.0 * win) / w if w > 0 else float(n)


